"""Checks emailforwardparser/literals.py against the patterns in regexs.py, and writes it:

    python -m tests.literals_test && black emailforwardparser/literals.py

A pattern is skipped when its literal is not in the string, so the table may only name text that
every match of the pattern contains. That is read here from the standard library's regex parser,
which is private to `re`: it writes and checks the table, and never runs in the library.
"""

import ast
import importlib
import re
from pathlib import Path
from typing import Any

import pytest

from emailforwardparser import forward_parser as fp, literals, loop, regexs
from emailforwardparser.literals import REQUIRED_LITERALS

sre = importlib.import_module("re._constants")
sre_parse = importlib.import_module("re._parser")

# Every list of patterns in regexs.py; the loop helpers only ever get these lists.
PATTERN_LISTS = {
    name: value
    for name, value in vars(regexs).items()
    if isinstance(value, list) and value and all(isinstance(item, re.Pattern) for item in value)
}
PATTERNS = [pattern for patterns in PATTERN_LISTS.values() for pattern in patterns]
REPEATS = (sre.MAX_REPEAT, sre.MIN_REPEAT, sre.POSSESSIVE_REPEAT)


def required_literal(pattern: re.Pattern[str]) -> str:
    """The longest run of literal text every match of `pattern` contains ("" when none is sure).

    Only items every match goes through count: literals at the top level, in groups and in
    repeats of at least one. A branch, an optional repeat, a lookaround, a character class or a
    case-insensitive pattern or group ends the run and adds nothing.
    """
    if pattern.flags & re.IGNORECASE:
        return ""
    best = ""

    def walk(items: Any) -> None:
        nonlocal best
        run = ""
        for op, argument in items:
            if op is sre.LITERAL:
                run += chr(argument)
                continue
            best = max(best, run, key=len)
            run = ""
            if op is sre.SUBPATTERN and not argument[1] & re.IGNORECASE:
                walk(argument[3])
            elif op in REPEATS and argument[0] >= 1:
                walk(argument[2])
            elif op is sre.ATOMIC_GROUP:
                walk(argument)
        best = max(best, run, key=len)

    walk(sre_parse.parse(pattern.pattern, pattern.flags))
    return best


def derived_table() -> dict[str, str]:
    table: dict[str, str] = {}
    for pattern in PATTERNS:
        literal = required_literal(pattern)
        if literal:
            table[pattern.pattern] = literal
    return table


def python_string(text: str) -> str:
    """`text` as a raw string literal, as regexs.py writes its patterns, where one can hold it."""
    raw = f'r"{text}"'
    try:
        if ast.literal_eval(raw) == text:
            return raw
    except SyntaxError:
        pass
    return repr(text)


def render() -> str:
    lines = [
        '"""Generated by tests/literals_test.py from regexs.py: do not edit by hand.',
        "",
        "For each pattern in regexs.py's lists, text that every match of it contains. A string",
        "without that text cannot match, so the loop helpers do not run the pattern on it.",
        '"""',
        "",
        "# Keyed by pattern source: every pattern in regexs.py carries its flags inline.",
        "REQUIRED_LITERALS: dict[str, str] = {",
    ]
    table = derived_table()
    lines += [f"    {python_string(source)}: {literal!r}," for source, literal in table.items()]
    lines.append("}")
    return "\n".join(lines) + "\n"


def test_the_table_is_what_the_patterns_require() -> None:
    assert derived_table() == REQUIRED_LITERALS


def test_a_pattern_source_says_everything_the_table_keys_on() -> None:
    for pattern in PATTERNS:
        assert re.compile(pattern.pattern).flags == pattern.flags


@pytest.mark.parametrize(
    ("pattern", "literal"),
    [
        (r"(?m)^Fw:(.*)", "Fw:"),
        (r"(?m)^(?:>\s*|[^\S\n]*)Begin forwarded message\s?:", "Begin forwarded message"),
        (r"^\s?\n?\s*<[^<>]+?<mailto\:(.+?)>>", "<mailto:"),
        (r"(?m)^Redir.:(.*)", "Redir"),
        (r"a(?:bc)+d", "bc"),
        (r"a(?:bcd)*e", "a"),
        (r"(?:ab|cd)e", "e"),
        (r"(?:abc|abd)e", "ab"),
        (r"x(?=abcd)", "x"),
        (r"(?>abcd)e", "abcd"),
        (r"(?i:abcd)e", "e"),
        (r"(?i)abcd", ""),
        (r"[ab]", ""),
    ],
)
def test_required_literal_takes_only_text_every_match_has(pattern: str, literal: str) -> None:
    assert required_literal(re.compile(pattern)) == literal


def test_a_string_without_the_literal_skips_the_pattern() -> None:
    pattern = regexs.SUBJECT[0]
    assert REQUIRED_LITERALS[pattern.pattern] == "Fw:"

    assert not loop.may_match(pattern, "Fwd: news")
    assert loop.may_match(pattern, "Fw: news")
    assert loop.may_match(re.compile(r"(?i)fw:"), "FW: news")


def test_only_the_first_three_mailbox_patterns_need_mailto() -> None:
    assert all("mailto:" in REQUIRED_LITERALS[pattern.pattern] for pattern in regexs.MAILBOX[:3])
    assert all(
        "mailto:" not in REQUIRED_LITERALS.get(pattern.pattern, "")
        for pattern in regexs.MAILBOX_WITHOUT_MAILTO
    )
    assert regexs.MAILBOX[3:] == regexs.MAILBOX_WITHOUT_MAILTO


@pytest.mark.parametrize(
    ("line", "mailboxes"),
    [
        (
            "To: Ann Lee <ann@example.com>, Bob <bob@example.com>",
            [("Ann Lee", "ann@example.com"), ("Bob", "bob@example.com")],
        ),
        (
            "To: Bob <mailto:bob@example.com>; Ann Lee <ann@example.com>",
            [("Bob", "bob@example.com"), ("Ann Lee", "ann@example.com")],
        ),
        (
            "To: <ann@example.com<mailto:ann@example.com>>, Bob [bob@example.com]",
            [("", "ann@example.com"), ("Bob", "bob@example.com")],
        ),
    ],
)
def test_recipient_lines_with_and_without_mailto(
    line: str, mailboxes: list[tuple[str, str]]
) -> None:
    parsed = fp.parse_mailbox(regexs.ORIGINAL_TO, line)

    assert [(mailbox.name, mailbox.address) for mailbox in parsed] == mailboxes


if __name__ == "__main__":
    Path(literals.__file__).write_text(render(), encoding="utf-8")
